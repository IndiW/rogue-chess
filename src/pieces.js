function pixelsPath(pixels) { return pixels.map(([x,y]) => `M${x} ${y}h1v1h-1z`).join(''); }
const paths = Object.fromEntries(Object.entries(art).map(([type, rows]) => {
  const silhouette = [], light = [], shade = [], detail = [];
  const filled = (x,y) => !!rows[y]?.[x] && rows[y][x] !== '.';
  rows.forEach((row,y) => [...row].forEach((value,x) => {
    if (value === '.') return;
    silhouette.push([x,y]);
    if (value === 'x') detail.push([x,y]);
    else if (!filled(x-1,y) || !filled(x,y-1)) light.push([x,y]);
    else if (!filled(x+1,y) || !filled(x,y+1)) shade.push([x,y]);
  }));
  return [type, {body:pixelsPath(silhouette),light:pixelsPath(light),shade:pixelsPath(shade),detail:pixelsPath(detail)}];
}));
export function sprite(type,color) {
  const p = paths[type];
  return `<svg viewBox="-1 -1 17 21" class="piece ${color}" aria-hidden="true"><ellipse class="ground-shadow" cx="7.5" cy="17.4" rx="6" ry="1.25"/><path class="outline" d="${p.body}"/><path d="${p.body}"/><path class="pixel-shade" d="${p.shade}"/><path class="pixel-light" d="${p.light}"/><path class="pixel-detail" d="${p.detail}"/></svg>`;
}
